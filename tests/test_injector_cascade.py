"""Cascade attribution wiring in the injector and the Markdown report.

The injector runs end to end against fakes on a virtual clock: no Docker, no network, no real sleeping.
`attribute()` is always monkeypatched, so these tests pin down the wiring (window arguments, failure
isolation, live view, report section), not the attribution rules themselves.
"""
from __future__ import annotations

from types import SimpleNamespace

import pytest

import faultline.agents.injector as injector_mod
from faultline.agents.injector import Injector
from faultline.chaos.actions import Handle
from faultline.observe.probes import HealthSample
from faultline.observe.window import Sample, SampleWindow
from faultline.reporting.markdown import experiment_markdown
from faultline.schemas import CascadeAttribution, CascadeEdge, CascadeHop, ExperimentSpec, Hypothesis

T0 = 1_700_000_000.0
TARGET = "policies"


# ---------------------------------------------------------------- fakes
class FakeHealth:
    """HealthProbe stand-in. Samples are generated by the virtual clock."""

    def __init__(self, services, interval=3.0, down=()):
        self.services, self.interval, self.down = list(services), interval, set(down)
        self.samples: list[HealthSample] = []
        self.fault = False

    def tick(self, ts: float) -> None:
        for svc in self.services:
            gone = self.fault and svc in self.down
            self.samples.append(HealthSample(ts, svc, "exited" if gone else "running", "healthy",
                                             None if gone else 200, None if gone else 200))

    def between(self, t0, t1=None):
        t1 = t1 if t1 is not None else float("inf")
        return [s for s in self.samples if t0 <= s.ts <= t1]

    def latest(self):
        out = {}
        for s in self.samples:
            out[s.service] = s
        return out

    def consecutive_failures(self, svc):  # keep the safety monitor out of the way
        return 0

    def all_healthy(self, services):
        return True


class Clock:
    """Virtual time. sleep() advances it, emitting an OK API sample every 0.25 s and a health tick per interval."""

    def __init__(self, window: SampleWindow, health: FakeHealth):
        self.now, self.window, self.health = T0, window, health
        self._next_health = T0

    def time(self) -> float:
        return self.now

    def sleep(self, dt: float) -> None:
        end = self.now + dt
        while self.now < end:
            self.now = round(self.now + 0.25, 6)
            self.window.add(Sample(self.now, "retrieve_thing", 200, 20.0))
            if self.now >= self._next_health:
                self.health.tick(self.now)
                self._next_health = self.now + self.health.interval


class FakeDocker:
    def __init__(self, target_status="running"):
        self.target_status = target_status

    def state(self, svc):
        return {"status": self.target_status if svc == TARGET else "running", "health": "healthy", "paused": False}

    def is_running(self, svc):
        return True

    def wait_running(self, svc, timeout):
        return True

    def logs(self, svc, since, tail=120):
        return ""

    def restart(self, svc):
        pass

    def start(self, svc):
        pass


class FakeHandle(Handle):
    def __init__(self, ctx, health: FakeHealth):
        super().__init__(ctx, "fake fault")
        self.health = health
        health.fault = True

    def _revert(self):
        self.health.fault = False


def _spec(**kw) -> ExperimentSpec:
    return ExperimentSpec(experiment_id=kw.pop("experiment_id", "exp-cascade"), target_service=TARGET,
                          container=f"bosch-ditto-{TARGET}-1", failure_type="container_crash",
                          parameters={"duration_s": 6}, rationale="test",
                          hypothesis=Hypothesis(statement="things degrade", expected_affected=["things"],
                                                expected_recovery_s=60),
                          criticality_score=1.0, planned_by="operator", **kw)


@pytest.fixture
def env(monkeypatch, topology, thresholds, tmp_store):
    """Build an Injector wired to fakes. `env(down=[...], target_status=...)` returns (injector, ctx namespace)."""

    def build(down=(), target_status="running"):
        window = SampleWindow()
        health = FakeHealth(topology.relevant_services(), down=down)
        clock = Clock(window, health)
        for i in range(80):  # steady pre-window
            ts = T0 - 20 + i * 0.25
            window.add(Sample(ts, "retrieve_thing", 200, 20.0))
        for k in range(7):
            health.tick(T0 - 21 + k * 3)
        monkeypatch.setattr(injector_mod, "time", clock)
        monkeypatch.setattr(injector_mod, "ACTIONS", {"container_crash": lambda ctx: FakeHandle(ctx, health)})
        live: list[dict] = []
        real_write_live = tmp_store.write_live

        def record_live(data):
            live.append(dict(data))
            real_write_live(data)

        monkeypatch.setattr(tmp_store, "write_live", record_live)
        api = SimpleNamespace(integrity_check=lambda: (True, "stored seq=1, last acknowledged write seq=1"))
        policy = SimpleNamespace(pre_window_s=10.0, min_pre_success=0.95, recovery_soak_s=4.0)
        inj = Injector(SimpleNamespace(), tmp_store, topology, FakeDocker(target_status), window, api, health,
                       thresholds, policy, log=lambda m: None)
        return inj, SimpleNamespace(window=window, health=health, clock=clock, live=live, store=tmp_store)

    return build


def _hop(service, mechanism, confidence, path, upstream=None, **kw) -> CascadeHop:
    return CascadeHop(service=service, onset_earliest_s=kw.pop("e", 0.0), onset_latest_s=kw.pop("l", 0.0),
                      onset_source=kw.pop("src", "health_probe"), mechanism=mechanism,
                      mechanism_evidence=kw.pop("ev", "synthetic"), upstream=upstream, path=path,
                      candidate_paths=[path], path_confidence=confidence, **kw)


def _attribution(origin=TARGET) -> CascadeAttribution:
    return CascadeAttribution(
        origin=origin, health_interval_s=3.0, window_start_s=-6.0, window_end_s=40.0,
        hops=[_hop(origin, "injected_fault", "origin", [origin], src="injection", ev="SIGKILL"),
              _hop("connectivity", "process_down", "ordered", ["connectivity", origin], upstream=origin,
                   e=0.5, l=3.0, lag_s=3.0, hops_from_origin=1, beyond_hypothesis=True)],
        edges=[CascadeEdge(src="connectivity", dst=origin, mechanism="process_down", confidence="ordered", lag_s=3.0)],
        beyond_hypothesis=["connectivity"], hops_beyond_hypothesis=1,
        notes=["health probe polls every 3s, so onsets are 3s intervals"])


class Recorder:
    def __init__(self, result=None, exc: Exception | None = None):
        self.calls: list[dict] = []
        self.result, self.exc = result, exc

    def __call__(self, **kw):
        self.calls.append(kw)
        if self.exc is not None:
            raise self.exc
        return self.result if self.result is not None else _attribution()


# ---------------------------------------------------------------- injector
def test_completed_run_carries_cascade_and_window_arguments(env, monkeypatch, topology):
    inj, ctx = env()
    rec = Recorder()
    monkeypatch.setattr(injector_mod, "attribute", rec)
    report = inj.run(_spec())

    assert report.status == "completed"
    assert report.cascade is not None and report.cascade.origin == TARGET
    assert [h.service for h in report.cascade.hops] == [TARGET, "connectivity"]

    final = rec.calls[-1]
    live_calls = rec.calls[:-1]
    assert live_calls, "provisional attribution should run during the fault"
    injected_at = final["injected_at"]
    revert_at = final["revert_at"]
    window_end = final["window_end"]
    assert final["topology"] is topology
    assert final["target"] == TARGET
    assert list(final["expected_affected"]) == ["things"]
    assert final["health_interval_s"] == 3.0
    assert final["baseline"] == report.baseline
    # the final window covers the fault, the recovery wait and the 8 s "after" window
    assert injected_at < revert_at < window_end
    assert window_end >= revert_at + 8
    assert window_end == pytest.approx(report.ended_at.timestamp(), abs=1e-3)
    hs = final["health_samples"]
    assert hs and min(s.ts for s in hs) >= injected_at - 2 * 3.0 and max(s.ts for s in hs) <= window_end
    assert any(s.ts < injected_at for s in hs), "health samples should reach back before injection"
    assert any(s.ts > revert_at for s in hs), "health samples should cover the recovery"
    api = final["api_samples"]
    assert api and min(s.ts for s in api) >= injected_at and max(s.ts for s in api) <= window_end
    # live calls: revert_at == window_end == "now", within the fault
    for c in live_calls:
        assert c["revert_at"] == c["window_end"]
        assert injected_at <= c["window_end"] <= revert_at
    # rate limited: at most one every 3 s over a 6 s fault
    assert len(live_calls) <= 2


def test_attribute_failure_does_not_alter_experiment(env, monkeypatch):
    inj_ok, _ = env(down=["connectivity"])
    monkeypatch.setattr(injector_mod, "attribute", Recorder(result=CascadeAttribution(
        origin=TARGET, health_interval_s=3.0, window_start_s=0, window_end_s=1)))
    ok = inj_ok.run(_spec())

    inj_bad, ctx = env(down=["connectivity"])
    boom = Recorder(exc=RuntimeError("boom"))
    monkeypatch.setattr(injector_mod, "attribute", boom)
    bad = inj_bad.run(_spec())

    assert len(boom.calls) >= 2  # live attempts + final attempt, all swallowed
    assert bad.cascade is None
    assert bad.status == ok.status == "completed"
    assert [f.model_dump() for f in bad.findings] == [f.model_dump() for f in ok.findings]
    assert bad.hypothesis_result == ok.hypothesis_result
    assert bad.recovery == ok.recovery
    assert bad.health == ok.health
    assert bad.affected_services_observed == ok.affected_services_observed
    failed = [e for e in bad.timeline if e.event == "cascade_attribution_failed"]
    assert len(failed) == 1 and failed[0].detail == "RuntimeError: boom"
    assert [e.event for e in bad.timeline if e.event != "cascade_attribution_failed"] == [e.event for e in ok.timeline]
    assert all("cascade_edges" not in d for d in ctx.live)
    assert (ctx.store.root / "experiments" / f"{bad.experiment_id}.json").exists()


def test_attribute_returning_wrong_type_is_treated_as_failure(env, monkeypatch):
    inj, _ = env()
    monkeypatch.setattr(injector_mod, "attribute", lambda **kw: {"not": "a model"})
    report = inj.run(_spec())
    assert report.status == "completed" and report.cascade is None
    assert any(e.event == "cascade_attribution_failed" and "TypeError" in e.detail for e in report.timeline)


def test_skipped_run_has_no_cascade(env, monkeypatch):
    inj, _ = env(target_status="exited")
    rec = Recorder()
    monkeypatch.setattr(injector_mod, "attribute", rec)
    report = inj.run(_spec())
    assert report.status == "skipped"
    assert report.cascade is None
    assert rec.calls == []


def test_cascade_finding_evidence_is_enriched_not_replaced(env, monkeypatch):
    inj_none, _ = env(down=["connectivity"])
    monkeypatch.setattr(injector_mod, "attribute", Recorder(exc=RuntimeError("off")))
    base = inj_none.run(_spec())

    inj, _ = env(down=["connectivity"])
    monkeypatch.setattr(injector_mod, "attribute", Recorder())
    report = inj.run(_spec())

    before = {f.code: f for f in base.findings}
    after = {f.code: f for f in report.findings}
    assert [(f.code, f.severity, f.title) for f in report.findings] == [(f.code, f.severity, f.title) for f in base.findings]
    assert "cascade_beyond_hypothesis" in after
    old, new = before["cascade_beyond_hypothesis"].evidence, after["cascade_beyond_hypothesis"].evidence
    assert new.startswith(old)
    assert f"{TARGET} → connectivity" in new and "process_down" in new
    for code in after:
        if code != "cascade_beyond_hypothesis":
            assert after[code].evidence == before[code].evidence


def test_live_json_carries_cascade_edges_and_keeps_last_value(env, monkeypatch):
    inj, ctx = env()
    attr = _attribution()
    calls = {"n": 0}

    def flaky(**kw):  # first provisional call works, later ones fail: the last good value must persist
        calls["n"] += 1
        if calls["n"] == 1:
            return attr
        raise ValueError("transient")

    monkeypatch.setattr(injector_mod, "attribute", flaky)
    inj.run(_spec())

    with_edges = [d for d in ctx.live if "cascade_edges" in d]
    assert with_edges
    assert with_edges[0]["cascade_edges"] == [e.model_dump() for e in attr.edges]
    assert with_edges[0]["cascade_hops"][1] == {"service": "connectivity", "mechanism": "process_down",
                                                "path_confidence": "ordered", "masked_by_health_check": False,
                                                "beyond_hypothesis": True}
    phases = {d["phase"] for d in with_edges}
    assert {"injecting", "rollback", "recovering"} <= phases
    # nothing before the first provisional attribution, and the idle marker stays bare
    assert "cascade_edges" not in ctx.live[0]
    assert ctx.live[-1] == {"phase": "idle", "experiment_id": "exp-cascade"}


# ---------------------------------------------------------------- markdown
def test_markdown_renders_cascade_section(make_report):
    r = make_report(service=TARGET, cascade=_attribution())
    md = experiment_markdown(r)
    assert "## Cascade" in md
    section = md.split("## Cascade", 1)[1].split("## Findings", 1)[0]
    assert f"- {TARGET} had the fault injected at +0.0s (SIGKILL)" in section
    assert f"- connectivity went down (container not running), first seen failing between +0.5s and +3.0s, " \
           f"after {TARGET} (path {TARGET} → connectivity) [beyond the hypothesis]" in section
    assert "- health probe polls every 3s, so onsets are 3s intervals" in section
    assert "| Service | onset | mechanism | via | confidence | masked |" in section
    assert f"| connectivity | +0.5s–+3.0s | process_down | {TARGET} | ordered | no |" in section
    assert f"| {TARGET} | +0.0s | injected_fault | — | origin | no |" in section


def test_markdown_omits_cascade_section_when_absent(make_report):
    r = make_report()
    assert r.cascade is None
    md = experiment_markdown(r)
    assert "## Cascade" not in md
    assert "Cascade" not in md
